export function inferToken(token) {
  const depth = Math.min(100, Math.round(18 * Math.log10(Math.max(token.liquidity, 1)) - 10))
  const flow = Math.min(100, Math.round(15 * Math.log10(Math.max(token.volume24, 1)) - 35))
  const balance = Math.min(token.buyers, token.sellers) / Math.max(token.buyers, token.sellers)
  const imbalance = Math.round((1 - balance) * 100)
  const turnover = token.volume24 / Math.max(token.liquidity, 1)
  const contamination = Math.min(99, Math.round(turnover / 3 + imbalance * 0.68 + (Math.abs(token.change1h) > 50 ? 16 : 0)))
  const persistence = Math.max(4, Math.min(96, Math.round(48 + token.change6h * 0.08 - Math.abs(token.change1h) * 0.14 + balance * 22)))
  const hype = Math.max(8, Math.min(98, Math.round(flow * 0.42 + persistence * 0.32 + Math.min(100, Math.abs(token.change24h) / 8) * 0.26)))

  return {
    depth,
    flow,
    imbalance,
    turnover,
    contamination,
    persistence,
    hype,
    confidence: Math.max(31, Math.min(91, Math.round(depth * 0.46 + (100 - contamination) * 0.42 + 12))),
    quarantined: contamination >= 70,
  }
}
